import numpy as np
import pandas as pd
import sys, os
from pathlib import Path

current_file = Path(__file__).resolve()
project_root = current_file.parent.parent

if str(project_root) not in sys.path:
	sys.path.append(str(project_root))

from tools.io import STRSUMMARY, AA2CG
from parameters.load_params import readParam

HPS_PROT = readParam(os.path.join(project_root, 'parameters/protein/hps_urry_parameters.csv'))
HPS_DNA  = readParam(os.path.join(project_root, 'parameters/dsDNA/hps_dsDNA.csv'))


def generateDATA(data, Mtype='DNA', fn_data='in.data', fn_lammps='lammps.in'):
	"""
		generate in.data file for LAMMPS
	"""

	info = STRSUMMARY(data, Mtype='DNA')
	L    = 500	

	CHN_DICT = {}
	for i, x in enumerate(info['chains']):
		CHN_DICT[x] = i+1


	ATM_DICT = {}
	for i,x in enumerate(info['atomtypes']):
		ATM_DICT[x] = i+1

	#print(ATM_DICT)

	with open(fn_data, 'w') as f:
		f.write('LAMMPS data generated by Qiang\n')	
		f.write('\n')
		f.write(' {:8d}\t atoms\n'.format(len(info['atoms'])))
		f.write(' {:8d}\t bonds\n'.format(len(info['bonds'])))
		f.write(' {:8d}\t angles\n'.format(len(info['angles'])))
		f.write('\n')
		f.write(' {:8d}\t atom types\n'.format(len(info['atomtypes'])))
		f.write(' {:8d}\t bond types\n'.format(2))
		f.write(' {:8d}\t angle types\n'.format(1))
		f.write('\n')
		f.write('{:10.6f} \t {:10.6f} \t xlo xhi\n'.format(-1*L, L))
		f.write('{:10.6f} \t {:10.6f} \t ylo yhi\n'.format(-1*L, L))
		f.write('{:10.6f} \t {:10.6f} \t zlo zhi\n'.format(-1*L, L))
		f.write('\n')
		f.write('Masses\n')
		f.write('\n')
		for k,v in ATM_DICT.items():
			f.write(' {:6d}\t{:10.6f}\n'.format(v, HPS_DNA.loc[HPS_DNA['atomtype']==k,'mass'].values[0]))
		f.write('\n')
		f.write('Atoms\n')
		f.write('\n')
		for i, row in data.iterrows():
			f.write('{:10d}\t{:5d}\t{:5d}\t{:>5.3f}\t{:>5.3f}\t{:>5.3f}\t{:>5.3f}\n'.format(
					i+1, CHN_DICT[row['chain']], ATM_DICT[row['name']], 
					HPS_DNA.loc[HPS_DNA['atomtype']==row['name'], 'charge'].values[0],
					row['xyz'][0], row['xyz'][1], row['xyz'][2]
			))
		f.write('\n')
		f.write('Bonds\n')
		f.write('\n')
		bond_idx = 0
		for i, row in data.iterrows():
			bondlist = row['bondlist']
			if len(bondlist) ==2:
				f.write('{:6d}\t{:6d}\t{:6d}\t{:6d}\n'.format(bond_idx+1, 1, i+1, bondlist[0]+1))
				bond_idx +=1
				f.write('{:6d}\t{:6d}\t{:6d}\t{:6d}\n'.format(bond_idx+1, 2, i+1, bondlist[1]+1))
				bond_idx +=1
			elif len(bondlist) == 1:
				f.write('{:6d}\t{:6d}\t{:6d}\t{:6d}\n'.format(bond_idx+1, 1, i+1, bondlist[0]+1))
				bond_idx +=1
		f.write('\n')

		f.write('Angles\n')
		f.write('\n')
		angle_idx = 0
		for i, row in data.iterrows():
			anglelist = row['anglelist']
			if len(anglelist):
				f.write('{:6d}\t{:6d}\t{:6d}\t{:6d}\t{:6d}\n'.format(angle_idx+1, 1, anglelist[0]+1, i+1, anglelist[1]+1))
				angle_idx +=1



